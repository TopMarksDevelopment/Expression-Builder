namespace ExpressionBuilder.Generators.Tests;

using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using TopMarksDevelopment.ExpressionBuilder.Api;
using TopMarksDevelopment.ExpressionBuilder.Generators;

public class FilterExtensionsGeneratorTests
{
    static readonly string[] Receivers =
    [
        "IFilter",
        "IFilter_TClass_",
        "IFilterable",
        "IFilterable_TClass_",
        "IQueryFilterable",
        "IQueryFilterable_TClass_",
    ];

    /// <summary>A minimal operation, marked as an operation package would mark its own.</summary>
    static string OperationSource(string name, string shape) =>
        $$"""
            namespace TopMarksDevelopment.ExpressionBuilder.Operations;

            using System.Linq.Expressions;
            using TopMarksDevelopment.ExpressionBuilder.Api;

            [GenerateFilterExtensions(FilterExtensionShape.{{shape}})]
            public struct {{name}} : IOperation
            {
                public string Name => "{{name}}";
                public OperationDefaults Defaults => new();
                public Expression Build<TPropertyType>(Expression member, IFilterCollection<TPropertyType?> values, IFilterStatementOptions? options)
                    => Expression.Constant(true);
                public void Validate(IFilterStatement statement) { }
            }
            """;

    static (
        Compilation Output,
        ImmutableArray<Diagnostic> Diagnostics,
        GeneratorDriverRunResult Run
    ) Generate(params string[] sources)
    {
        // Everything the running tests can see (the runtime, plus the API the generated code uses)
        var references = (
            (string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!
        )
            .Split(Path.PathSeparator)
            .Select(path => MetadataReference.CreateFromFile(path));

        var compilation = CSharpCompilation.Create(
            "Operations.Sample",
            sources.Select(source => CSharpSyntaxTree.ParseText(source)),
            references,
            new CSharpCompilationOptions(
                OutputKind.DynamicallyLinkedLibrary,
                nullableContextOptions: NullableContextOptions.Enable
            )
        );

        GeneratorDriver driver = CSharpGeneratorDriver.Create(
            new FilterExtensionsGenerator()
        );
        driver = driver.RunGeneratorsAndUpdateCompilation(
            compilation,
            out var output,
            out var diagnostics
        );

        return (output, diagnostics, driver.GetRunResult());
    }

    static int CountMethods(Compilation compilation, string receiver, string op)
    {
        var type = compilation.GetTypeByMetadataName(
            $"TopMarksDevelopment.ExpressionBuilder.{receiver}{op}Extensions"
        );

        Assert.NotNull(type);

        return type.GetMembers(op)
            .OfType<IMethodSymbol>()
            .Count(m => m.DeclaredAccessibility == Accessibility.Public);
    }

    [Theory(
        DisplayName = "Each shape generates its set of overloads on every receiver"
    )]
    [InlineData("Values", 16)]
    [InlineData("Range", 16)]
    [InlineData("None", 8)]
    public void GeneratesTheOverloadsOfAShape(string shape, int overloads)
    {
        var (output, diagnostics, run) = Generate(
            OperationSource("Sample", shape)
        );

        Assert.Empty(diagnostics);
        Assert.Empty(
            output
                .GetDiagnostics()
                .Where(d => d.Severity == DiagnosticSeverity.Error)
        );

        // The attribute, plus one file for each receiver
        Assert.Equal(
            Receivers.Select(r => $"Sample.{r}.g.cs").Order(),
            run.Results.Single()
                .GeneratedSources.Select(s => s.HintName)
                .Where(n => n.StartsWith("Sample."))
                .Order()
        );

        foreach (var receiver in Receivers)
            Assert.Equal(overloads, CountMethods(output, receiver, "Sample"));
    }

    [Fact(DisplayName = "The generated methods are named after the operation")]
    public void NamesAreTakenFromTheOperation()
    {
        var (_, _, run) = Generate(OperationSource("Frobnicate", "Values"));

        var generated = run
            .Results.Single()
            .GeneratedSources.Where(s => s.HintName.StartsWith("Frobnicate."));

        Assert.All(
            generated,
            s =>
            {
                var text = s.SourceText.ToString();

                Assert.DoesNotContain("__Op__", text);
                Assert.Contains("new Frobnicate()", text);
                Assert.Contains("Operations.Frobnicate\"/>", text);
                Assert.StartsWith("// <auto-generated/>", text);
            }
        );
    }

    [Fact(DisplayName = "Every generated method is documented")]
    public void MethodsAreDocumented()
    {
        var (_, _, run) = Generate(OperationSource("Sample", "Range"));

        foreach (
            var source in run
                .Results.Single()
                .GeneratedSources.Where(s => s.HintName.StartsWith("Sample."))
        )
        {
            var text = source.SourceText.ToString();

            Assert.Equal(
                CountOf(text, "    public static "),
                CountOf(text, "    /// <summary>Adds a statement")
            );
        }

        static int CountOf(string text, string value) =>
            text.Split([value], StringSplitOptions.None).Length - 1;
    }

    [Fact(DisplayName = "Several operations can be generated together")]
    public void SeveralOperations()
    {
        var (output, diagnostics, _) = Generate(
            OperationSource("First", "Values"),
            OperationSource("Second", "None")
                .Replace(
                    "namespace TopMarksDevelopment.ExpressionBuilder.Operations;",
                    "namespace Elsewhere;\nusing TopMarksDevelopment.ExpressionBuilder.Operations;"
                )
        );

        Assert.Empty(diagnostics);
        Assert.Empty(
            output
                .GetDiagnostics()
                .Where(d => d.Severity == DiagnosticSeverity.Error)
        );
        Assert.Equal(16, CountMethods(output, "IFilter", "First"));
        Assert.Equal(8, CountMethods(output, "IFilter", "Second"));
    }

    [Fact(DisplayName = "A type without the attribute is left alone")]
    public void IgnoresUnmarkedTypes()
    {
        var (_, _, run) = Generate("namespace Sample; public struct Plain { }");

        Assert.Equal(
            [$"{GenerateFilterExtensionsAttribute.Name}.g.cs"],
            run.Results.Single().GeneratedSources.Select(s => s.HintName)
        );
    }

    [Theory(DisplayName = "Every template exists")]
    [InlineData("Values")]
    [InlineData("Range")]
    [InlineData("None")]
    public void TemplatesExist(string shape)
    {
        foreach (var receiver in Receivers)
            Assert.Contains(
                "public static partial class",
                FilterExtensionsGenerator.ReadTemplate(shape, receiver)
            );
    }

    [Fact(
        DisplayName = "The generated code matches the API's own extension methods for the same receiver"
    )]
    public void ReceiversAreTheApiInterfaces()
    {
        // The templates name these interfaces, so a rename in the API must be noticed here
        var api = typeof(IFilter).Assembly;

        foreach (var receiver in Receivers)
            Assert.NotNull(
                api.GetType(
                    $"TopMarksDevelopment.ExpressionBuilder.Api.{receiver.Replace("_TClass_", "`1")}"
                )
            );
    }
}
