namespace TopMarksDevelopment.ExpressionBuilder.Generators;

/// <summary>
/// The source of the attribute that operations are annotated with. It is added to each operation
/// project's compilation (as an <c>internal</c> type) rather than shipped as a dependency, so the
/// generator stays a build-time detail.
/// </summary>
static class GenerateFilterExtensionsAttribute
{
    public const string Namespace =
        "TopMarksDevelopment.ExpressionBuilder.Operations";

    public const string Name = "GenerateFilterExtensionsAttribute";

    public const string FullName = Namespace + "." + Name;

    public const string Source = """
        // <auto-generated/>
        #nullable enable
        namespace TopMarksDevelopment.ExpressionBuilder.Operations;

        /// <summary>
        /// The shapes of value list an operation accepts. Each shape produces the matching set of
        /// <c>Filter</c>/<c>Filterable</c>/<c>QueryFilterable</c> extension methods.
        /// </summary>
        internal enum FilterExtensionShape
        {
            /// <summary>One value, or an array of values (e.g. <c>Equal</c>, <c>Contains</c>, <c>In</c>).</summary>
            Values,

            /// <summary>An array of values, or exactly two (e.g. <c>Between</c>).</summary>
            Range,

            /// <summary>No values at all (e.g. <c>IsNull</c>).</summary>
            None,
        }

        /// <summary>
        /// Marks an operation so that its fluent extension methods are generated at build time,
        /// instead of being copied by hand for every operation.
        /// </summary>
        [global::System.AttributeUsage(
            global::System.AttributeTargets.Struct | global::System.AttributeTargets.Class,
            AllowMultiple = false,
            Inherited = false
        )]
        internal sealed class GenerateFilterExtensionsAttribute(FilterExtensionShape shape)
            : global::System.Attribute
        {
            /// <summary>The shape of the values the operation accepts.</summary>
            public FilterExtensionShape Shape { get; } = shape;
        }
        """;
}
