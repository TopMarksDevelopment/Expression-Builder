namespace TopMarksDevelopment.ExpressionBuilder.Generators;

using System.Collections.Immutable;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

/// <summary>
/// Generates the fluent extension methods (<c>filter.Equal(...)</c>) for every operation marked with
/// <c>[GenerateFilterExtensions]</c>.
/// </summary>
/// <remarks>
/// Every operation exposes the same overloads on the same six receivers, differing only by name and
/// by how many values it takes. The overloads are therefore kept once, as the templates under
/// <c>Templates/</c>, and stamped out per operation here.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class FilterExtensionsGenerator : IIncrementalGenerator
{
    const string OperationPlaceholder = "__Op__";

    static readonly string[] Shapes = ["Values", "Range", "None"];

    static readonly string[] Receivers =
    [
        "IFilter",
        "IFilter_TClass_",
        "IFilterable",
        "IFilterable_TClass_",
        "IQueryFilterable",
        "IQueryFilterable_TClass_",
    ];

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(c =>
            c.AddSource(
                GenerateFilterExtensionsAttribute.Name + ".g.cs",
                SourceText.From(
                    GenerateFilterExtensionsAttribute.Source,
                    Encoding.UTF8
                )
            )
        );

        var operations = context
            .SyntaxProvider.ForAttributeWithMetadataName(
                GenerateFilterExtensionsAttribute.FullName,
                static (node, _) => true,
                static (ctx, _) => ToOperation(ctx)
            )
            .Where(static o => o is not null)
            .Select(static (o, _) => o!.Value);

        context.RegisterSourceOutput(operations, static (c, op) => Emit(c, op));
    }

    static OperationInfo? ToOperation(GeneratorAttributeSyntaxContext context)
    {
        var attribute = context.Attributes[0];

        if (
            attribute.ConstructorArguments.Length != 1
            || attribute.ConstructorArguments[0].Value is not int shape
        )
            return null;

        // The enum lives in the consuming compilation (see the attribute source), so its
        // members are mapped here by value, in declaration order.
        return shape >= 0 && shape < Shapes.Length
            ? new OperationInfo(
                context.TargetSymbol.Name,
                context.TargetSymbol.ContainingNamespace.ToDisplayString(),
                Shapes[shape]
            )
            : null;
    }

    static void Emit(SourceProductionContext context, OperationInfo operation)
    {
        foreach (var receiver in Receivers)
        {
            var template = ReadTemplate(operation.Shape, receiver);

            context.AddSource(
                $"{operation.Name}.{receiver}.g.cs",
                SourceText.From(
                    Render(template, operation.Name, operation.Namespace),
                    Encoding.UTF8
                )
            );
        }
    }

    internal static string Render(
        string template,
        string operationName,
        string operationNamespace
    )
    {
        // The templates are written for operations in the standard namespace
        var source = template
            .Replace(OperationPlaceholder, operationName)
            .Replace(
                "using TopMarksDevelopment.ExpressionBuilder.Operations;",
                $"using {operationNamespace};"
            );
        var operation =
            $"<see cref=\"global::{operationNamespace}.{operationName}\"/>";

        // The templates hold only code; the XML docs are identical for every overload, so they are
        // added here rather than repeated 16 times in each of the 18 templates.
        source = Regex.Replace(
            source,
            @"^public static partial class",
            m =>
                $"/// <summary>Fluent methods that apply the {operation} operation.</summary>\n{m.Value}",
            RegexOptions.Multiline
        );
        source = Regex.Replace(
            source,
            @"^    public static (?!partial)",
            m =>
                $"    /// <summary>Adds a statement that applies the {operation} operation.</summary>\n{m.Value}",
            RegexOptions.Multiline
        );

        return "// <auto-generated/>\n#nullable enable\n\n" + source;
    }

    internal static string ReadTemplate(string shape, string receiver)
    {
        var assembly = typeof(FilterExtensionsGenerator).Assembly;

        // Resource names are prefixed with the project's root namespace, which is not the
        // assembly name, so match on the part that is ours.
        var suffix = $".Templates.{shape}.{receiver}.template";
        var resource =
            assembly
                .GetManifestResourceNames()
                .SingleOrDefault(n => n.EndsWith(suffix))
            ?? throw new InvalidOperationException(
                $"The template '{suffix}' is missing from the generator."
            );

        using var stream = assembly.GetManifestResourceStream(resource)!;
        using var reader = new StreamReader(stream, Encoding.UTF8);

        return reader.ReadToEnd();
    }

    readonly record struct OperationInfo(
        string Name,
        string Namespace,
        string Shape
    );
}
